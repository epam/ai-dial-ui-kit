interface FileGlyphProps {
  size: number;
  kind: FileGlyphKind;
}

/**
 * The 2.0 file glyph: a gradient sheet with the line work of its kind.
 * Design system 2.0
 *
 * Inlined for the same reasons as `FolderGlyph`: a per-instance gradient `id`
 * from `useId`, and theme tokens in place of fixed hex values.
 *
 * @param size - Width and height in px
 * @param kind - Which art to draw
 */
export const FileGlyph: FC<FileGlyphProps> = ({ size, kind }) => {
  // `useId` output contains `:` or `«»`, which are unsafe inside `url(#…)`.
  const gradientId = `dial-kit-file-gradient-${useId().replace(/[^\w-]/g, '')}`;
  const { path, fillPath, sheet } = GLYPH_ART[kind];
  const isFlat = typeof sheet === 'string';

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 20 20"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
    >
      <path
        d="M17.4999 3.97859V16C17.4999 18.2091 15.709 20 13.4999 20H6.5C4.29086 20 2.5 18.2091 2.5 16V4C2.5 1.79086 4.29086 0 6.5 0H13.1683H13.5213C15.7186 0 17.4999 1.78128 17.4999 3.97859Z"
        fill={isFlat ? sheet : `url(#${gradientId})`}
      />
      {path && (
        <path
          d={path}
          stroke={MARK_COLOR}
          strokeWidth="0.7"
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      )}
      {fillPath && <path d={fillPath} fill={MARK_COLOR} />}
      {!isFlat && (
        <defs>
          <linearGradient
            id={gradientId}
            x1={sheet.x1}
            y1={sheet.y1}
            x2={sheet.x2}
            y2={sheet.y2}
            gradientUnits="userSpaceOnUse"
          >
            <stop stopColor={sheet.from} />
            <stop offset="1" stopColor={sheet.to} />
          </linearGradient>
        </defs>
      )}
    </svg>
  );
};
